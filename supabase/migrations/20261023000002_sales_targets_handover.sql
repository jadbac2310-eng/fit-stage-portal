alter table public.sales_target_logs add column if not exists kind        text not null default 'メモ';
alter table public.sales_target_logs add column if not exists occurred_at timestamptz;
alter table public.sales_target_logs add column if not exists person      text;
alter table public.sales_target_logs add column if not exists event_id    uuid references public.personal_events(id) on delete set null;

create index if not exists idx_sales_target_logs_occurred on public.sales_target_logs (target_id, occurred_at desc);

