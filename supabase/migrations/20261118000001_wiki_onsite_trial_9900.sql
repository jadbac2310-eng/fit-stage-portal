-- ハンドブック：出張の体験は 9,900円（店舗の体験は 6,600円のまま）
-- 2026-11-18 尚樹「出張の場合は体験も全部とりあえず9,900円」。HPも同日に変更済み。
-- 何回流しても同じ結果（すでに直っていれば何も変わらない）。

-- 1) サービスと料金：出張の表に体験の行を足す
update public.wiki_pages
   set content = replace(content,
         E'## 出張パーソナル（HPから直接のお申し込み）\n\n| | 料金 |\n|---|---|\n| 1名60分 | ¥9,900 |',
         E'## 出張パーソナル（HPから直接のお申し込み）\n\n| | 料金 |\n|---|---|\n| 体験 1名60分 | ¥9,900（出張の体験は通常の1名60分と同じ額。店舗の体験 ¥6,600 とは別） |\n| 1名60分 | ¥9,900 |'),
       updated_at = now()
 where content like E'%## 出張パーソナル（HPから直接のお申し込み）\n\n| | 料金 |\n|---|---|\n| 1名60分 | ¥9,900 |%';

-- 2) お客さま対応のルール／体験レッスンの流れ：体験の金額の書き方
update public.wiki_pages
   set content = replace(
                   replace(content,
                     '体験は有料（1名60分 ¥6,600）。',
                     '体験は有料（店舗：1名60分 ¥6,600／出張：1名60分 ¥9,900）。'),
                   '有料（1名60分 ¥6,600・ペア ¥9,900）',
                   '有料（店舗：1名60分 ¥6,600・ペア ¥9,900／出張：1名60分 ¥9,900）'),
       updated_at = now()
 where content like '%体験は有料（1名60分 ¥6,600）。%'
    or content like '%有料（1名60分 ¥6,600・ペア ¥9,900）%';

-- 確認：直ったページ（3ページ出れば完了。「サービスと料金」「お客さま対応のルール」「体験レッスンの流れ」）
select slug, title from public.wiki_pages
 where content like '%出張の体験は通常の1名60分と同じ額%'
    or content like '%出張：1名60分 ¥9,900%'
 order by title;
