// 日替わりで出るもの（格言のほかに、お題・豆知識・運勢）。
//
// 格言と同じで、日付から1つに決まる。データベースは使わない。
// 「今日は何が出るかな」を毎日つくるのが目的なので、どれも日替わりにしている。

const JST = 9 * 3600 * 1000;

function jstDayNumber(now: Date | number = Date.now()): number {
  const t = typeof now === "number" ? now : now.getTime();
  return Math.floor((t + JST) / 86400000);
}

/** 日付から決める（リストごとに少しずらして、同じ日に偏らないようにする） */
function pick<T>(list: T[], now: Date | number, offset: number): T {
  return list[(jstDayNumber(now) + offset) % list.length];
}

