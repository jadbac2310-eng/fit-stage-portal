const JST = 9 * 3600 * 1000;

/** 日本時間で何日目か（1970-01-01 を 0 とする通し日数） */
function jstDayNumber(now: Date | number = Date.now()): number {
  const t = typeof now === "number" ? now : now.getTime();
  return Math.floor((t + JST) / 86400000);
}

/**
 * その日の格言。日付から決まるので、同じ日なら誰が開いても同じものが出る。
 * 日数 % 件数 なので、件数ぶんの日数で一巡する。
 */
export function quoteOfTheDay(now: Date | number = Date.now()): DailyQuote {
  return DAILY_QUOTES[jstDayNumber(now) % DAILY_QUOTES.length];
}
