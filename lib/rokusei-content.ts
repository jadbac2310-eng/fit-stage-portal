/**
 * 星まわりの文章。全部ここ。
 *
 * 書き方の決まり（心理学の知見にそろえてある）：
 *   ・必ず前向きに書く。「失敗する」「災い」は使わない。
 *     ポジティブな占い文を読んだ人は、信じていなくても課題の成績が上がった（Brown ほか, Ursinus College）。
 *     逆にネガティブな文は読み飛ばされやすい。
 *   ・「だから今日これをやる」まで書く。運気を読んだだけでは行動は変わらない。
 *     小さく具体的な一手（Tiny Habits／実行意図）にして、やった実感（小さな勝ち）を作る。
 *   ・大殺界は「ダメな時期」ではなく「充電・準備・足元を固める時期」として書く。
 *     幸運のおまじないは自信（自己効力感）を通して成果を上げる（Damisch ほか 2010）。不安をあおる文は逆効果。
 *   ・FIT STAGE の仕事（体験・声かけ・回数券・お客様の記録）に必ず結びつける。
 *   ・月初・年初など「区切り」は新しく始めやすい（フレッシュスタート効果）。種子・再会で後押しする。
 */

