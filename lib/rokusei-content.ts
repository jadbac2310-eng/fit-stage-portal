export function starText(star: Star, polarity: Polarity): { catch: string; traits: string; work: string; lead: string; note: string } {
  const t = STAR_TEXT[star];
  return { catch: t.catch, traits: t.traits, work: t.work, lead: t.lead, note: polarity === "+" ? t.plus : t.minus };
}

/** 殺界の表示名 */
export function phaseBadge(phase: Phase): string | null {
  if (phase === "陰影" || phase === "停止" || phase === "減退") return "充電期（大殺界）";
  if (phase === "乱気") return "守りの時期（中殺界）";
  if (phase === "健弱") return "休む時期（小殺界）";
  return null;
}

/** 今日のひとつ。日ごと・人ごとに変える（同じ日・同じ人なら同じ） */
export function tipOfDay(phase: Phase, seed: number): string {
  const tips = PHASE_TEXT[phase].tips;
  return tips[((seed % tips.length) + tips.length) % tips.length];
}
